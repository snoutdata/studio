import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildHistoryComment, isBrowseShaped, relevantHistory } from './historyContext';
import type { QueryHistoryEntry } from '../../queries';

function ok(sql: string, connectionId: string): QueryHistoryEntry {
	return { sql, connectionId, connectionLabel: connectionId, timestamp: 0, outcome: { ok: true, rowCount: 1, durationMs: 1 } };
}

function failed(sql: string, connectionId: string): QueryHistoryEntry {
	return { sql, connectionId, connectionLabel: connectionId, timestamp: 0, outcome: { ok: false, error: 'boom' } };
}

// Newest-first, as QueryStore returns it.
const history: QueryHistoryEntry[] = [
	ok('SELECT * FROM orders WHERE status = 1', 'c1'),
	ok('SELECT name FROM customers', 'c1'),
	ok('SELECT id FROM orders JOIN order_items ON order_items.order_id = orders.id', 'c1'),
	ok('SELECT * FROM products', 'c2'),
	failed('DELETE FROM orders', 'c1'),
];

test('ranks by token overlap and scopes to successful queries on the same connection', () => {
	const picks = relevantHistory('SELECT count(*) FROM orders WHERE ', 'c1', history);
	const sqls = picks.map((p) => p.sql);
	// Both order queries match "orders"; customers/products/failed are excluded.
	assert.deepEqual(sqls, [
		'SELECT * FROM orders WHERE status = 1',
		'SELECT id FROM orders JOIN order_items ON order_items.order_id = orders.id',
	]);
});

test('a non-matching prefix yields nothing (no random history injected)', () => {
	assert.deepEqual(relevantHistory('SELECT * FROM widgets', 'c1', history), []);
});

test('an empty prefix yields nothing — recency is not relevance', () => {
	// The old fallback dumped "the most recent N" into the prompt with no signal at all, which is
	// how machine-generated browse queries ended up as the thing the model copied.
	assert.deepEqual(relevantHistory('', 'c1', history), []);
});

test('no connection means no history (table names would not line up)', () => {
	assert.deepEqual(relevantHistory('SELECT * FROM orders', undefined, history), []);
});

test('the query currently being typed is not offered back as an example', () => {
	const picks = relevantHistory('select * from orders where status = 1', 'c1', history);
	assert.ok(!picks.some((p) => p.sql.toLowerCase() === 'select * from orders where status = 1'));
});

test('maxExamples caps how many are returned', () => {
	const picks = relevantHistory('SELECT count(*) FROM orders WHERE ', 'c1', history, { maxExamples: 1 });
	assert.equal(picks.length, 1);
	assert.equal(picks[0].sql, 'SELECT * FROM orders WHERE status = 1');
});

// On a database with hundreds of tables, `select * from cus‸` could complete to
// `customer_order_check_status ORDER BY `id` LIMIT 200 OFFSET 0` — copied straight off a history
// line the explorer had generated by clicking that table once.
const browseHeavy: QueryHistoryEntry[] = [
	ok('select  * from shop_prod.customer_order_check_status ORDER BY `id` LIMIT 200 OFFSET 0', 'c1'),
	ok('select  * from shop_prod.order_item_ship_status ORDER BY `id` LIMIT 200 OFFSET 0', 'c1'),
	ok('SELECT c.name, co.id FROM customer c JOIN customer_order co ON co.customer_id = c.id WHERE c.id = 5', 'c1'),
	ok('SELECT c.name, co.id FROM customer c JOIN customer_order co ON co.customer_id = c.id WHERE c.id = 9', 'c1'),
	ok('SELECT count(*) FROM customer WHERE country_id = 3', 'c1'),
];

test('excludes the explorer\'s own browse queries', () => {
	assert.equal(isBrowseShaped('select  * from shop_prod.customer_order_check_status ORDER BY `id` LIMIT 200 OFFSET 0'), true);
	assert.equal(isBrowseShaped('SELECT * FROM orders'), true);
	// A filter the user typed makes it theirs again.
	assert.equal(isBrowseShaped('SELECT * FROM orders WHERE status = 1 ORDER BY id LIMIT 200'), false);
	assert.equal(isBrowseShaped('SELECT name FROM customers'), false);
});

test('the regression: a half-typed table name retrieves what you actually write', () => {
	const picks = relevantHistory('select * from cus', 'c1', browseHeavy);
	assert.ok(picks.length > 0, 'expected the hand-written customer queries');
	// Nothing machine-generated survives, so there is no browse statement left to copy.
	assert.ok(!picks.some((p) => /check_status|ship_status/.test(p.sql)), picks.map((p) => p.sql).join('\n'));
	assert.ok(picks.every((p) => /customer/i.test(p.sql)));
});

test('one query run many times is one example, not many', () => {
	// The two customer/customer_order queries differ only in a literal — same shape.
	const picks = relevantHistory('select * from cus', 'c1', browseHeavy);
	const joins = picks.filter((p) => p.sql.includes('JOIN customer_order'));
	assert.equal(joins.length, 1);
});

test('a shared table outranks loose word overlap', () => {
	const entries: QueryHistoryEntry[] = [
		ok('SELECT id, name, status FROM widget WHERE status = 1', 'c1'),
		ok('SELECT count(*) FROM orders WHERE created_at > now()', 'c1'),
	];
	const picks = relevantHistory('SELECT status, name, id FROM orders WHERE ', 'c1', entries);
	assert.equal(picks[0].sql, 'SELECT count(*) FROM orders WHERE created_at > now()');
});

test('ranks against the current statement, not the whole document', () => {
	const entries: QueryHistoryEntry[] = [
		ok('SELECT * FROM invoice WHERE paid = 1', 'c1'),
		ok('SELECT * FROM orders WHERE status = 2', 'c1'),
	];
	// A big earlier statement about invoices must not steer a fresh statement about orders.
	const document = 'SELECT invoice.id, invoice.total FROM invoice WHERE invoice.paid = 1;\n\nSELECT * FROM orders WHERE ';
	const picks = relevantHistory(document, 'c1', entries);
	assert.equal(picks[0].sql, 'SELECT * FROM orders WHERE status = 2');
});

test('buildHistoryComment renders every line as a SQL comment', () => {
	const comment = buildHistoryComment('SELECT count(*) FROM orders WHERE ', 'c1', history);
	assert.match(comment, /^-- Examples of SQL you have written/);
	for (const line of comment.split('\n')) {
		assert.ok(line.startsWith('--'), `not a comment line: ${line}`);
	}
	assert.match(comment, /SELECT \* FROM orders WHERE status = 1/);
});

test('buildHistoryComment is empty when nothing is relevant', () => {
	assert.equal(buildHistoryComment('SELECT * FROM widgets', 'c1', history), '');
});
